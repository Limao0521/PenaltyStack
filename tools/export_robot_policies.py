def fmt(value, digits=9):
    value = float(value)
    if not math.isfinite(value):
        raise ValueError('non-finite parameter')
    text = '%.*g' % (digits, value)
    return '0' if text in ('0', '-0') else text


def cfg_array(values, digits=9, per_line=8):
    values = [fmt(v, digits) for v in np.asarray(values).ravel()]
    lines = [', '.join(values[i:i + per_line]) for i in range(0, len(values), per_line)]
    return '[\n    ' + ',\n    '.join(lines) + '\n  ]'


def layer_cfg(weight, bias):
    weight, bias = np.asarray(weight), np.asarray(bias)
    return ('{\n  rows = %d;\n  cols = %d;\n  weights = %s;\n  bias = %s;\n}'
            % (weight.shape[0], weight.shape[1], cfg_array(weight), cfg_array(bias)))


def export_striker(name, directory):
    from penalty.rl import striker_preserving_policy  # noqa: F401  (custom SB3 class of v4)
    from penalty.rl.duel import export_trained
    spec = export_trained(ROOT / directory)
    if spec['role'] != 'striker':
        raise ValueError('%s is not a striker policy' % directory)
    params = spec['params']
    hidden = [(np.asarray(w, np.float32), np.asarray(b, np.float32)) for w, b in params['pi']]
    (action_w, action_b), = params['action']
    action_w, action_b = np.asarray(action_w, np.float32), np.asarray(action_b, np.float32)
    mean, var = np.asarray(spec['mean'], np.float64), np.asarray(spec['var'], np.float64)
    text = ['// Generated by tools/export_robot_policies.py from %s. Do not edit.' % directory,
            '// Deterministic SB3 actor: clip(mean), tanh MLP, frozen VecNormalize (rl_obs_v1).',
            'name = "%s";' % name,
            'history = %d;' % spec['history'],
            'obsMean = %s;' % cfg_array(mean, 17),
            'obsVar = %s;' % cfg_array(var, 17),
            'clipObs = %s;' % fmt(spec['clip'], 17),
            'epsilon = %s;' % fmt(spec['epsilon'], 17),
            'hidden = [\n%s\n];' % ',\n'.join(layer_cfg(w, b) for w, b in hidden),
            'action = %s;' % layer_cfg(action_w, action_b)]
    data = ('\n'.join(text) + '\n').encode('utf-8')
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / (name + '.cfg')).write_bytes(data)
    # Exact numbers as the robot parses them (float32 weights printed with 9 digits round-trip).
    golden = {'name': name, 'history': spec['history'], 'obsMean': mean.tolist(), 'obsVar': var.tolist(),
              'clipObs': float(spec['clip']), 'epsilon': float(spec['epsilon']),
              'hidden': [{'weights': w.astype(np.float64).tolist(), 'bias': b.astype(np.float64).tolist()}
                         for w, b in hidden],
              'action': {'weights': action_w.astype(np.float64).tolist(),
                         'bias': action_b.astype(np.float64).tolist()}}
    return spec, golden, hashlib.sha256(data).hexdigest()


def striker_samples(spec, rng, count=64):
    from penalty.rl.duel import NumpyTrainedPolicy
    policy = NumpyTrainedPolicy(spec)
    cases = []
    for episode in range(count // 8):
        policy.reset()
        steps = []
        for step in range(8):
            obs = np.array([
                .1 * step + rng.uniform(0, 3), rng.uniform(.05, .6), rng.uniform(-.25, .25),
                rng.normal(0, .3), rng.normal(0, .3), rng.choice([0., .1, .3]),
                rng.uniform(1.2, 1.8), rng.uniform(-.2, .2), rng.uniform(-math.pi, math.pi),
                rng.uniform(-.3, .3), rng.uniform(-.8, -.3), rng.uniform(.3, .8),
                rng.normal(0, .05), rng.normal(0, .05), rng.normal(0, .2), rng.normal(0, .2), rng.normal(0, .2),
                rng.uniform(0, 28), float(rng.random() > .1)])
            if episode == 0 and step == 0:
                obs[3] = 50.  # exercises clip_observation
            clipped = clip_observation(obs)
            normalized = policy(clipped)
            action = StrikerAction.from_normalized(normalized)
            steps.append({'observation': obs.tolist(), 'normalized': normalized.astype(np.float64).tolist(),
                          'target_y': action.target_y, 'right_foot': bool(action.kick_side == 1),
                          'power': action.kick_power, 'trigger': action.trigger})
        cases.append(steps)
    return cases


def observation_cases(rng, count=6):
    cases = []
    for _ in range(count):
        builder = ObservationBuilder()
        steps = []
        robot = [geometry.STRIKER_START[0][0], 0., math.pi]
        ball = [geometry.PENALTY_MARK[0] + rng.normal(0, .03), rng.normal(0, .03)]
        for step in range(12):
            t = .1 * step
            robot[0] -= rng.uniform(0, .02)
            robot[1] += rng.normal(0, .005)
            robot[2] = geometry.wrap(robot[2] + rng.normal(0, .02))
            if step > 8:
                ball[0] -= rng.uniform(.1, .3)
                ball[1] += rng.normal(0, .05)
            visible = bool(rng.random() > .2)
            state = WorldState(time_s=t, remaining_time=geometry.PENALTY_SECONDS - t, ball_xy=tuple(ball),
                               robot_xy=(robot[0], robot[1]), robot_yaw=robot[2],
                               opponent_xy=geometry.KEEPER_START[0], opponent_yaw=geometry.KEEPER_START[1],
                               torso_roll=rng.normal(0, .02), torso_pitch=rng.normal(0, .02),
                               gyro=tuple(rng.normal(0, .1, 3)), ball_visible=visible)
            obs = builder.build(state).to_array().astype(np.float64)
            steps.append({'state': {'time': t, 'remaining': geometry.PENALTY_SECONDS - t, 'ball': list(ball),
                                    'robot': list(robot), 'opponent': [*geometry.KEEPER_START[0], geometry.KEEPER_START[1]],
                                    'torso_roll': state.torso_roll, 'torso_pitch': state.torso_pitch,
                                    'gyro': list(state.gyro), 'ball_visible': visible},
                          'observation': dict(zip(OBSERVATION_FIELDS, map(float, obs)))})
        cases.append(steps)
    return cases


def keeper_cases(rng, modes=('balanced', 'original'), count=24):
    """Synthetic shots at 30 Hz seen from a standing keeper (ground frame = odometry)."""
    cases = []
    for index in range(count):
        mode = modes[index % len(modes)]
        keeper = VisionLibraryKeeper(mode)
        tracker = BallTracker()
        target_y = rng.uniform(-.75, .75)
        start = np.array([1.3 + rng.normal(0, .03), rng.normal(0, .03)])
        speed = rng.uniform(.8, 2.2)
        direction = np.array([-.12 - start[0], target_y - start[1]])
        velocity = direction / np.linalg.norm(direction) * speed
        kick_time = rng.uniform(.5, 1.5)
        odometry = (rng.normal(0, .01), rng.normal(0, .01), rng.normal(0, .02))
        steps = []
        for frame in range(int(3.2 * 30)):
            capture = frame / 30.
            moving = max(0., capture - kick_time)
            truth = start + velocity * moving
            seen = rng.random() > .1 and truth[0] > -.2
            measurement = None
            if seen:
                sigma = .01 + .02 * float(np.hypot(*truth))
                world = truth + rng.normal(0, sigma, 2)
                c, s = math.cos(odometry[2]), math.sin(odometry[2])
                dx, dy = world[0] - odometry[0], world[1] - odometry[1]
                local = (c * dx + s * dy, -s * dx + c * dy)
                measurement = {'position': local, 'covariance': ((sigma ** 2, 0.), (0., sigma ** 2))}
            tracker.update(capture, capture, measurement, odometry)
            ball = tracker.estimate(capture, odometry)
            state = {'version': STATE_VERSION, 'time_s': capture, 'capture_s': capture,
                     'remaining_time': max(0., 28. - capture), 'ball': ball}
            action = keeper(state)
            decision = keeper.decision
            steps.append({'capture': capture, 'odometry': list(odometry),
                          'measurement': None if measurement is None else
                          {'position': list(measurement['position']),
                           'covariance': [list(r) for r in measurement['covariance']]},
                          'estimate': {'position': list(ball['position']), 'velocity': list(ball['velocity']),
                                       'position_valid': ball['position_valid'],
                                       'velocity_valid': ball['velocity_valid'], 'visible': ball['visible'],
                                       'age_s': ball['age_s'], 'reason': ball['reason'],
                                       'velocity_variance_x': ball['velocity_covariance'][0][0]},
                          'defense': action.defense, 'trigger': action.trigger,
                          'reason': decision['reason'], 'crossing_y': decision.get('crossing_y')})
        cases.append({'mode': mode, 'steps': steps})
    return cases


def registry(striker_hashes):
    policies = {'version': 'copa_penalty_policies_v1', 'striker': {}, 'keeper': {}}
    for name, (status, text) in BASELINES['striker'].items():
        policies['striker'][name] = {'status': status, 'description': text, 'file': None}
    for name, (directory, status, text) in STRIKERS.items():
        entry = MANIFEST.get(name, {})
        policies['striker'][name] = {'status': status, 'description': text, 'file': name + '.cfg',
                                     'sha256': striker_hashes[name], 'source': directory,
                                     'manifest_status': entry.get('estado')}
    for name, (status, text) in BASELINES['keeper'].items():
        policies['keeper'][name] = {'status': status, 'description': text, 'file': None}
    policies['defaults'] = {'striker': 'striker_v2', 'keeper': 'vision_v2_balanced'}
    return policies


def main():
    parser = argparse.ArgumentParser(description='Export NAO policies and parity goldens.')
    parser.add_argument('--seed', type=int, default=20261103)
    args = parser.parse_args()
    rng = np.random.default_rng(args.seed)
    golden = {'version': 'copa_golden_v1', 'seed': args.seed, 'strikers': {}}
    hashes = {}
    for name, (directory, _, _) in STRIKERS.items():
        spec, params, digest = export_striker(name, directory)
        hashes[name] = digest
        golden['strikers'][name] = {'policy': params, 'cases': striker_samples(spec, rng)}
        print('exported %-24s sha256=%s' % (name, digest))
    golden['observations'] = observation_cases(rng)
    golden['keepers'] = keeper_cases(rng)
    (OUT / 'policies.json').write_text(json.dumps(registry(hashes), indent=2, ensure_ascii=False) + '\n',
                                       encoding='utf-8')
    GOLDEN.parent.mkdir(parents=True, exist_ok=True)
    GOLDEN.write_text(json.dumps(golden) + '\n', encoding='utf-8')
    print('wrote %s and %s' % (OUT / 'policies.json', GOLDEN))


if __name__ == '__main__':
    main()
