"""Rollout workers for asynchronous PPO collection (numpy policy, no torch).

Each worker owns one environment and streams transitions generated by the
policy version it was last sent. Protocol over a duplex Pipe:

  learner -> worker: ('run', payload) | ('pause', None) | ('close', None)
  worker -> learner: ('ready', None) | ('t', transition) | ('e', evaluation)
                     | ('paused', bootstrap) | ('error', traceback)

With spec['eval_every'] = k > 0, every k-th episode is played with the mean
action (as a deployed policy acts). Those episodes send only their record
('e') and never enter the PPO rollout.
"""
import math
import traceback

import numpy as np

LOG_SQRT_2PI = .5*math.log(2*math.pi)


class NumpyPolicy:
    """Forward pass of an SB3 ActorCriticPolicy exported by
    penalty.rl.async_ppo.export_policy: separate tanh MLPs for actor and
    critic and a state-independent diagonal Gaussian."""

    def __init__(self, params):
        def layers(name):
            return [(np.asarray(w, np.float64), np.asarray(b, np.float64)) for w, b in params[name]]
        self.pi, self.vf = layers('pi'), layers('vf')
        (self.action_w, self.action_b), = layers('action')
        (self.value_w, self.value_b), = layers('value')
        self.log_std = np.asarray(params['log_std'], np.float64)
        self.std = np.exp(self.log_std)

    @staticmethod
    def _mlp(x, layers):
        for w, b in layers:
            x = np.tanh(w @ x + b)
        return x

    def mean(self, obs):
        return self.action_w @ self._mlp(np.asarray(obs, np.float64), self.pi) + self.action_b

    def value(self, obs):
        return float((self.value_w @ self._mlp(np.asarray(obs, np.float64), self.vf) + self.value_b)[0])

    def log_prob(self, mean, action):
        z = (np.asarray(action, np.float64) - mean)/self.std
        return float(np.sum(-.5*z*z - self.log_std - LOG_SQRT_2PI))

    def act(self, obs, rng):
        """Unclipped float32 sample (as SB3 stores it), its log-prob and V(obs)."""
        mean = self.mean(obs)
        action = (mean + self.std*rng.standard_normal(mean.shape)).astype(np.float32)
        return action, self.log_prob(mean, action), self.value(obs)


def normalize(obs, stats):
    """VecNormalize.normalize_obs with frozen statistics."""
    mean, var, clip, epsilon = stats
    return np.clip((obs - mean)/np.sqrt(var + epsilon), -clip, clip).astype(np.float32)


def worker(conn, spec):
    env = None
    try:
        from penalty.rl.training import build_env
        env = build_env(spec['role'], spec['backend'], spec['opponent'], spec['backend_options'],
                        spec['seed'], monitor=False)
        low, high = env.action_space.low, env.action_space.high
        rng = np.random.default_rng(spec['seed'])
        raw, _ = env.reset(seed=spec['seed'])
        episode_start, episode_return, episode_length = True, 0., 0
        eval_every, episodes, evaluating = spec.get('eval_every', 0), 0, False
        policy = stats = gamma = None
        running = False
        conn.send(('ready', None))
        while True:
            if not running or conn.poll():
                command, payload = conn.recv()
                if command == 'run':
                    policy, stats, gamma = NumpyPolicy(payload['policy']), payload['obs'], payload['gamma']
                    running = True
                elif command == 'pause':
                    running = False
                    conn.send(('paused', {'value': policy.value(normalize(raw, stats))}))
                elif command == 'close':
                    return
                continue
            obs = normalize(raw, stats)
            if evaluating:
                action = np.clip(policy.mean(obs), low, high).astype(np.float32)
                raw, _, terminated, truncated, info = env.step(action)
                if terminated or truncated:
                    conn.send(('e', {'eval_record': info.get('episode_record', {})}))
                    raw, _ = env.reset()
                    episodes += 1
                    evaluating = episodes % eval_every == 0
                    episode_start = True
                continue
            action, log_prob, value = policy.act(obs, rng)
            next_raw, reward, terminated, truncated, info = env.step(np.clip(action, low, high))
            episode_return += reward
            episode_length += 1
            done = terminated or truncated
            if truncated and not terminated:  # SB3: bootstrap a time-limit cut with V(terminal obs)
                reward += gamma*policy.value(normalize(next_raw, stats))
            transition = {'obs': obs, 'raw': raw, 'action': action, 'log_prob': log_prob,
                          'value': value, 'reward': float(reward), 'episode_start': episode_start,
                          'done': done, 'info': {}}
            if done:
                transition['info']['episode'] = {'r': episode_return, 'l': episode_length}
                if 'episode_record' in info:
                    transition['info']['episode_record'] = info['episode_record']
                next_raw, _ = env.reset()
                episode_return, episode_length = 0., 0
                episodes += 1
                evaluating = bool(eval_every) and episodes % eval_every == 0
            episode_start = done
            raw = next_raw
            conn.send(('t', transition))
    except (EOFError, BrokenPipeError, KeyboardInterrupt):
        pass  # the learner is gone
    except Exception:
        try:
            conn.send(('error', traceback.format_exc()))
        except (OSError, EOFError):
            pass
    finally:
        if env is not None:
            env.close()
